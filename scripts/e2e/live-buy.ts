import { TGAS, USDC, account, call, near, view } from "../lib.js";
const estate = "playground.plote.testnet", usdc = "musdc.plote.testnet", buyerId = "buyer-2.plote.testnet", unitId = process.argv[2] ?? "p-55";
const t0 = Date.now(); const lap = () => `${((Date.now() - t0) / 1000).toFixed(1)}s`;
const u0 = await view<any>(estate, "get_unit", { unit_id: unitId });
console.log("unit before:", u0.status, "price", Number(BigInt(u0.price) / USDC), "USDC, account", u0.account);
const est = await view<any>(estate, "get_estate", {});
console.log("estate params:", JSON.stringify({ playground: est.params.playground, min_first_bps: est.params.min_first_payment_bps, mobilisation: est.params.mobilisation_bps, veto_ns: est.params.veto_window_ns }));
const buyer = account(buyerId);
const bal0 = BigInt(await view<string>(usdc, "ft_balance_of", { account_id: buyerId }));
const tenPct = BigInt(u0.price) / 10n;
await call(buyer, usdc, "mint", { amount: tenPct.toString() }, { deposit: near("0.00125"), gas: 30n * TGAS });
console.log(lap(), "minted", Number(tenPct / USDC), "test USDC; balance", Number((BigInt(await view<string>(usdc, "ft_balance_of", { account_id: buyerId })) - bal0) / USDC), "new");
await call(buyer, estate, "reserve", { unit_id: unitId }, { deposit: near("0.05"), gas: 30n * TGAS });
console.log(lap(), "reserved:", (await view<any>(estate, "get_unit", { unit_id: unitId })).status);
await call(buyer, usdc, "ft_transfer_call", { receiver_id: u0.account, amount: tenPct.toString(), msg: "" }, { deposit: 1n, gas: 200n * TGAS });
const u1 = await view<any>(estate, "get_unit", { unit_id: unitId });
console.log(lap(), "after pay:", u1.status, "holder", u1.holder, "paid", Number(BigInt(u1.paid) / USDC), "released", u1.released, "releasable", u1.releasable_now);
console.log("unit account USDC:", Number(BigInt(await view<string>(usdc, "ft_balance_of", { account_id: u0.account })) / USDC));
const tok = await view<any>(estate, "nft_token", { token_id: unitId });
console.log("NFT owner:", tok?.owner_id, "title:", tok?.metadata?.title);
const svg = Buffer.from(tok.metadata.media.replace(/^data:image\/svg\+xml;base64,/, ""), "base64").toString();
console.log("NFT media orange:", svg.includes("#FF9211"), "teal:", svg.includes("#2DD4BF"));
console.log("nft_supply_for_owner:", await view(estate, "nft_supply_for_owner", { account_id: buyerId }));
